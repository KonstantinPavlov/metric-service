package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"strings"
)

type TargetStruct struct {
	Name   string
	Struct *ast.StructType
}

func main() {
	log.Println("=== Старт генератора Reset ===")
	
	// Находим абсолютный путь корня, чтобы go/parser не терял файлы
	wd, err := os.Getwd()
	if err != nil {
		log.Fatalf("Не удалось получить рабочую директорию: %v", err)
	}

	err = filepath.Walk(wd, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}

		if info.IsDir() {
			// Пропускаем служебные директории
			if strings.HasPrefix(info.Name(), ".") || info.Name() == "vendor" {
				return filepath.SkipDir
			}
			// Пропускаем саму папку генератора
			if info.Name() == "reset" && strings.Contains(path, "cmd") {
				return filepath.SkipDir
			}
			
			// Обрабатываем конкретную директорию пакета
			processPackage(path)
		}
		return nil
	})

	if err != nil {
		log.Fatalf("Ошибка сканирования проекта: %v", err)
	}
	log.Println("=== Сканирование завершено ===")
}

func processPackage(dirPath string) {
	fset := token.NewFileSet()
	
	// Парсим файлы по абсолютному пути
	pkgs, err := parser.ParseDir(fset, dirPath, func(info os.FileInfo) bool {
		return !strings.HasSuffix(info.Name(), "_test.go") && info.Name() != "reset.gen.go"
	}, parser.ParseComments)
	
	if err != nil {
		return
	}

	for pkgName, pkg := range pkgs {
		var targets []TargetStruct

		for _, file := range pkg.Files {
			// 1. Проверяем, содержит ли вообще этот файл маркер "generate:reset"
			hasDirectiveInFile := false
			for _, commentGroup := range file.Comments {
				for _, comment := range commentGroup.List {
					cleanText := strings.ReplaceAll(comment.Text, " ", "")
					if strings.Contains(cleanText, "generate:reset") {
						hasDirectiveInFile = true
						break
					}
				}
			}

			// Если в файле нет маркера, этот файл вообще не разбираем
			if !hasDirectiveInFile {
				continue
			}

			// Выводим лог, что файл зацепил наше внимание
			log.Printf("Найдена директива в файле: %s (пакет %s)", filepath.Base(fset.File(file.Pos()).Name()), pkgName)

			// 2. Ищем саму структуру в файле
			ast.Inspect(file, func(n ast.Node) bool {
				genDecl, ok := n.(*ast.GenDecl)
				if !ok || genDecl.Tok != token.TYPE {
					return true
				}

				for _, spec := range genDecl.Specs {
					typeSpec, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}

					structType, ok := typeSpec.Type.(*ast.StructType)
					if !ok {
						continue
					}

					// Железобетонная проверка: если маркер есть в файле, добавляем структуры из этого объявления
					targets = append(targets, TargetStruct{
						Name:   typeSpec.Name.Name,
						Struct: structType,
					})
				}
				return true
			})
		}

		if len(targets) > 0 {
			err := generateResetFile(dirPath, pkgName, targets)
			if err != nil {
				log.Printf("ОШИБКА генерации для пакета %s: %v", pkgName, err)
				return
			}
			fmt.Printf(" [УСПЕХ] Сгенерирован reset.gen.go для пакета %s в %s\n", pkgName, dirPath)
		}
	}
}

func generateResetFile(dirPath, pkgName string, targets []TargetStruct) error {
	var buf bytes.Buffer

	buf.WriteString(fmt.Sprintf("// Code generated by cmd/reset. DO NOT EDIT.\npackage %s\n\n", pkgName))

	for _, t := range targets {
		receiver := strings.ToLower(t.Name[:1])
		if receiver == "_" {
			receiver = "r"
		}

		buf.WriteString(fmt.Sprintf("func (%s *%s) Reset() {\n", receiver, t.Name))
		buf.WriteString(fmt.Sprintf("\tif %s == nil {\n\t\treturn\n\t}\n\n", receiver))

		for _, field := range t.Struct.Fields.List {
			if len(field.Names) == 0 {
				continue
			}

			for _, name := range field.Names {
				fieldName := name.Name
				writeFieldReset(&buf, receiver, fieldName, field.Type)
			}
		}

		buf.WriteString("}\n\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		_ = os.WriteFile(filepath.Join(dirPath, "reset.gen.go"), buf.Bytes(), 0644)
		return fmt.Errorf("ошибка форматирования: %w (сырой файл сохранен для анализа)", err)
	}

	return os.WriteFile(filepath.Join(dirPath, "reset.gen.go"), formatted, 0644)
}

func writeFieldReset(buf *bytes.Buffer, receiver, fieldName string, expr ast.Expr) {
	switch t := expr.(type) {
	case *ast.Ident:
		buf.WriteString(fmt.Sprintf("\t%s.%s = %s\n", receiver, fieldName, getZeroValue(t.Name)))

	case *ast.ArrayType:
		if t.Len == nil {
			buf.WriteString(fmt.Sprintf("\t%s.%s = %s.%s[:0]\n", receiver, fieldName, receiver, fieldName))
		} else {
			buf.WriteString(fmt.Sprintf("\tfor i := range %s.%s {\n", receiver, fieldName))
			buf.WriteString(fmt.Sprintf("\t\tvar zero %s\n", exprToString(t.Elt)))
			buf.WriteString(fmt.Sprintf("\t\t%s.%s[i] = zero\n", receiver, fieldName))
			buf.WriteString("\t}\n")
		}

	case *ast.MapType:
		buf.WriteString(fmt.Sprintf("\tclear(%s.%s)\n", receiver, fieldName))

	case *ast.StarExpr:
		buf.WriteString(fmt.Sprintf("\tif %s.%s != nil {\n", receiver, fieldName))
		if isIdentOrSelector(t.X) {
			buf.WriteString(fmt.Sprintf("\t\tif resetter, ok := interface{}(%s.%s).(interface{ Reset() }); ok {\n", receiver, fieldName))
			buf.WriteString("\t\t\tresetter.Reset()\n")
			buf.WriteString("\t\t} else {\n")
			buf.WriteString(fmt.Sprintf("\t\t\t*%s.%s = %s\n", receiver, fieldName, getZeroValue(exprToString(t.X))))
			buf.WriteString("\t\t}\n")
		} else {
			buf.WriteString(fmt.Sprintf("\t\t*%s.%s = %s\n", receiver, fieldName, getZeroValue(exprToString(t.X))))
		}
		buf.WriteString("\t}\n")

	default:
		buf.WriteString(fmt.Sprintf("\tif resetter, ok := interface{}(&%s.%s).(interface{ Reset() }); ok {\n", receiver, fieldName))
		buf.WriteString("\t\tresetter.Reset()\n")
		buf.WriteString(fmt.Sprintf("\t} else if resetter, ok := interface{}(%s.%s).(interface{ Reset() }); ok {\n", receiver, fieldName))
		buf.WriteString("\t\tresetter.Reset()\n")
		buf.WriteString("\t} else {\n")
		buf.WriteString(fmt.Sprintf("\t\t%s.%s = %s\n", receiver, fieldName, getZeroValue(exprToString(expr))))
		buf.WriteString("\t}\n")
	}
}

func getZeroValue(typeName string) string {
	switch typeName {
	case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "byte", "rune":
		return "0"
	case "float32", "float64":
		return "0.0"
	case "string":
		return `""`
	case "bool":
		return "false"
	default:
		if strings.HasPrefix(typeName, "map") || strings.HasPrefix(typeName, "[]") || strings.HasPrefix(typeName, "*") {
			return "nil"
		}
		return typeName + "{}"
	}
}

func isIdentOrSelector(expr ast.Expr) bool {
	_, isIdent := expr.(*ast.Ident)
	_, isSelector := expr.(*ast.SelectorExpr)
	return isIdent || isSelector
}

func exprToString(expr ast.Expr) string {
	var buf bytes.Buffer
	if err := format.Node(&buf, token.NewFileSet(), expr); err != nil {
		return ""
	}
	return buf.String()
}
